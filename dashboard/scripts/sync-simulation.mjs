// Builds src/utils/simulation_results.json from the simulation output.
//
//   npm run sync:simulation        (npm.cmd on Windows PowerShell)
//
// Source: database/seed/simulation_results.json, written by algorithm/simulate.py.
// The dashboard is deployed from this folder alone, so it cannot read the
// database folder at build time. Run this again whenever the simulation is
// re-run and commit the result. Never edit the output by hand.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../../database/seed/simulation_results.json', import.meta.url));
const target = fileURLToPath(new URL('../src/utils/simulation_results.json', import.meta.url));

if (!existsSync(source)) {
  console.error(`Not found: ${source}\nRun "python simulate.py" in the algorithm folder first.`);
  process.exit(1);
}

const results = JSON.parse(readFileSync(source, 'utf8'));
results._note = 'GENERATED by dashboard/scripts/sync-simulation.mjs from database/seed/simulation_results.json. Do not edit by hand. Synthetic data.';

writeFileSync(target, `${JSON.stringify(results)}\n`);
console.log(`Wrote ${target}`);
