// Builds src/utils/benchmark_results.json from the real benchmark output.
//
//   npm run sync:benchmark        (npm.cmd on Windows PowerShell)
//
// Source: database/seed/benchmark_results.json, written by algorithm/benchmark.py.
// The dashboard is deployed from this folder alone, so it cannot read the
// database folder at build time. Run this again whenever the benchmark is re-run
// and commit the result. Never edit the output by hand.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../../database/seed/benchmark_results.json', import.meta.url));
const target = fileURLToPath(new URL('../src/utils/benchmark_results.json', import.meta.url));

if (!existsSync(source)) {
  console.error(`Not found: ${source}\nRun "python benchmark.py" in the algorithm folder first.`);
  process.exit(1);
}

const results = JSON.parse(readFileSync(source, 'utf8'));

const NAMES = {
  fcfs: 'FCFS',
  greedy: 'Greedy',
  genetic: 'Genetic',
  hybrid: 'Hybrid',
};
const METRICS = [
  'gini_coefficient',
  'avg_response_time_estimate',
  'high_severity_rate',
  'low_income_coverage',
  'computational_time_ms',
  'sampi_wait_correlation',
  'mean_leg_km',
];

const round = (value) => (value === null || value === undefined ? null : Number(value.toFixed(4)));
const pick = (stats) => Object.fromEntries(METRICS.map((m) => [m, { mean: round(stats[m].mean), sd: round(stats[m].sd) }]));

const cfg = results.config;
const output = {
  _note: 'GENERATED by dashboard/scripts/sync-benchmark.mjs from database/seed/benchmark_results.json. Do not edit by hand. Synthetic data.',
  config: {
    datasets: cfg.datasets,
    requestsPerDataset: cfg.requests_per_dataset,
    workersPerDataset: cfg.workers_per_dataset,
    wards: cfg.wards,
    geneticGenerations: cfg.genetic_generations,
    hybridAlpha: cfg.hybrid_alpha,
    highSeverityTopShare: cfg.high_severity_top_share,
    lowIncomeTopShare: cfg.low_income_top_share,
    lowIncomeSampiThreshold: cfg.low_income_sampi_threshold,
    shareInLowIncomeWards: cfg.share_of_requests_in_low_income_wards,
  },
  metricNotes: results.metric_notes,
  algorithms: Object.keys(NAMES).map((key) => ({
    key,
    name: key === 'hybrid' ? `Hybrid (alpha ${cfg.hybrid_alpha})` : NAMES[key],
    metrics: pick(results.summary[key]),
  })),
  alphaSensitivity: results.alpha_sensitivity.map((row) => ({
    alpha: row.alpha,
    metrics: pick(row.metrics),
  })),
};

writeFileSync(target, `${JSON.stringify(output, null, 2)}\n`);
console.log(`Wrote ${target}`);
